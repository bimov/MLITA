from OpenRouterChat import send_message

# ==== Системный промпт ====
SYSTEM_PROMPT = """Ты — экспертный ассистент по формальной логике. 
Преобразуй текстовую задачу на естественном языке в набор формул логики предикатов.

Правила:
1. Выведи ТОЛЬКО формулы, разделённые запнятыми. Без пояснений, примеров, нумерации или слов.
2. Формулы должны быть вида: Предикат(Объект) или ¬Предикат(Объект).
3. Допустимые логические связки: ¬, ∧, ∨, →.
4. Допустимо использовать переменные (x, y, z) и константы (Сократ, Петя и т.п.).
5. Для всеобщих утверждений используй явный квантор всеобщности ∀, например: ∀x (Человек(x) → Смертен(x)).
6. Для экзистенциальных утверждений используй квантор существования ∃, например: ∃x (Птица(x) ∧ УмеетЛетать(x)).

Пример:
Вход: 'Сократ — человек. Все люди смертны. Докажи, что Сократ смертен.'
Выход: 'Человек(Сократ), ∀x (Человек(x) → Смертен(x)), Смертен(Сократ)'
"""

# ==== Специализированная функция для логических задач ====
def convert_to_predicate_logic(user_text: str) -> str:
    """
    Преобразует текстовую задачу на естественном языке в формулы логики предикатов.
    """
    # Формируем полный промпт с системными инструкциями и задачей
    full_prompt = f"{SYSTEM_PROMPT}\n\nЗадача: {user_text}"
    return send_message(full_prompt)


def run_tests():
    """Запускает тесты преобразования логических выражений."""
    test_inputs = [
        "Сократ — человек. Все люди смертны. Докажи, что Сократ смертен.",
        "Если кто-то человек, то он смертен.",
        "Существует кто-то, кто говорит правду и бессмертен.",
        "Сократ — человек. Все люди смертны. Докажи, что Сократ смертен.",
        "Все кошки — животные. Мурка — кошка. Докажи, что Мурка — животное.",
        "Некоторые птицы умеют летать. Пингвин — птица. Докажи, что пингвин умеет летать.",
        "Если идет дождь, то улица мокрая. Улица мокрая. Докажи, что идет дождь.",
        "Все студенты сдают экзамены. Петя — студент. Докажи, что Петя сдает экзамены."
    ]
    
    for inp in test_inputs:
        print(f"\nВход: {inp}")
        try:
            result = convert_to_predicate_logic(inp)
            print("Выход:", result)
        except Exception as e:
            print(f"Ошибка: {e}")

# ==== Точка входа ====
if __name__ == "__main__":
    run_tests()
